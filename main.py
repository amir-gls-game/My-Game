import pygame

from stage1 import Stage1
from stage2 import Stage2
from Transition import Transition


pygame.init()


# =================================================
# اندازه صفحه
# =================================================

WIDTH = 720
HEIGHT = 1280


# =================================================
# صفحه اصلی
# =================================================

screen = pygame.display.set_mode(
    (WIDTH, HEIGHT)
)


pygame.display.set_caption(
    "My Game"
)


clock = pygame.time.Clock()


# =================================================
# مرحله فعلی
# =================================================

stage = Stage1(
    screen
)


# =================================================
# مرحله بعد
# =================================================

next_stage = None


# =================================================
# Transition
# =================================================

transition = Transition(
    distance=HEIGHT,
    duration=2.0
)


transition_started = False


# =================================================
# Surface مرحله اول
# =================================================

stage_surface = pygame.Surface(
    (WIDTH, HEIGHT)
)


# =================================================
# Surface مرحله دوم
# =================================================

next_stage_surface = pygame.Surface(
    (WIDTH, HEIGHT)
)


# =================================================
# محل اولیه بازیکن مرحله اول
# =================================================

transition_player_start_x = 0
transition_player_start_y = 0


# =================================================
# رسم یک مرحله روی Surface مشخص
# =================================================

def draw_stage_to_surface(
    current_stage,
    surface
):

    # ---------------------------------------------
    # صفحه فعلی مرحله را ذخیره می‌کنیم
    # ---------------------------------------------

    old_screen = (
        current_stage.screen
    )

    # ---------------------------------------------
    # موقتاً Surface را صفحه مرحله می‌کنیم
    # ---------------------------------------------

    current_stage.screen = (
        surface
    )

    # ---------------------------------------------
    # پاک کردن Surface
    # ---------------------------------------------

    surface.fill(
        (0, 0, 0)
    )

    # ---------------------------------------------
    # رسم کامل مرحله
    # ---------------------------------------------

    current_stage.draw()

    # ---------------------------------------------
    # برگرداندن صفحه اصلی
    # ---------------------------------------------

    current_stage.screen = (
        old_screen
    )


# =================================================
# حلقه اصلی
# =================================================

running = True


while running:

    # =================================================
    # زمان این فریم
    # =================================================

    dt = (
        clock.tick(60)
        / 1000.0
    )

    # جلوگیری از پرش در صورت افت فریم
    if dt > 0.05:

        dt = 0.05

    # =================================================
    # EVENT
    # =================================================

    for event in pygame.event.get():

        # ---------------------------------------------
        # خروج
        # ---------------------------------------------

        if event.type == pygame.QUIT:

            running = False

            continue

        # ---------------------------------------------
        # هنگام Transition
        #
        # هیچ کنترل دستی پذیرفته نمی‌شود
        # ---------------------------------------------

        if transition.is_active():

            continue

        # ---------------------------------------------
        # رویداد مرحله فعلی
        # ---------------------------------------------

        stage.handle_event(
            event
        )

    # =================================================
    # UPDATE
    # =================================================

    if not transition.is_active():

        stage.update()

    # =================================================
    # شروع Transition
    # =================================================

    if (
        hasattr(
            stage,
            "next_stage"
        )
        and
        stage.next_stage == "stage2"
        and
        not transition_started
    ):

        # ---------------------------------------------
        # ساخت مرحله ۲
        # ---------------------------------------------

        next_stage = Stage2(
            screen
        )

        # ---------------------------------------------
        # ذخیره موقعیت بازیکن
        # ---------------------------------------------

        transition_player_start_x = (
            stage.player.x
        )

        transition_player_start_y = (
            stage.player.y
        )

        # ---------------------------------------------
        # شروع Transition
        # ---------------------------------------------

        transition.start()

        transition_started = True

    # =================================================
    # UPDATE TRANSITION
    # =================================================

    if transition.is_active():

        # ---------------------------------------------
        # آپدیت Transition
        # ---------------------------------------------

        transition.update(
            dt
        )

        # ---------------------------------------------
        # مقدار حرکت
        #
        # 0 → 720
        # ---------------------------------------------

        offset = (
            transition.get_offset()
        )

        # ---------------------------------------------
        # بازیکن به صورت نرم به سمت بالا می‌رود
        # ---------------------------------------------

        stage.player.x = (
            transition_player_start_x
        )

        stage.player.y = (
            transition_player_start_y
            - offset
        )

    # =================================================
    # DRAW
    # =================================================

    if not transition_started:

        # ---------------------------------------------
        # حالت عادی
        # ---------------------------------------------

        stage.draw()

    else:

        # =================================================
        # ساخت تصویر ثابت مرحله اول
        # =================================================

        draw_stage_to_surface(
            stage,
            stage_surface
        )

        # =================================================
        # ساخت تصویر ثابت مرحله دوم
        # =================================================

        draw_stage_to_surface(
            next_stage,
            next_stage_surface
        )

        # =================================================
        # پاک کردن صفحه
        # =================================================

        screen.fill(
            (0, 0, 0)
        )

        # =================================================
        # مقدار حرکت
        # =================================================

        offset = (
            transition.get_offset()
        )

        # =================================================
        # مرحله اول
        #
        # از بالا به پایین حرکت می‌کند
        # =================================================

        screen.blit(
            stage_surface,
            (
                0,
                offset
            )
        )

        # =================================================
        # مرحله دوم
        #
        # از بالا وارد صفحه می‌شود
        # =================================================

        screen.blit(
            next_stage_surface,
            (
                0,
                offset - HEIGHT
            )
        )

    # =================================================
    # پایان Transition
    # =================================================

    if (
        transition.is_finished()
        and
        transition_started
    ):

        # ---------------------------------------------
        # مرحله دوم تبدیل به مرحله فعلی می‌شود
        # ---------------------------------------------

        stage = next_stage

        next_stage = None

        transition_started = False

        # ---------------------------------------------
        # بازیکن دقیقاً در محل شروع مرحله ۲
        # ---------------------------------------------

        stage.player.x = (
            stage.start_player_x
        )

        stage.player.y = (
            stage.start_player_y
        )

    # =================================================
    # نمایش
    # =================================================

    pygame.display.flip()


# =================================================
# خروج
# =================================================

pygame.quit()